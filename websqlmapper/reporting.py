from __future__ import annotations

import html
import json
from pathlib import Path
from typing import Any


def _as_dict(report: Any) -> dict[str, Any]:
    if hasattr(report, "to_dict"):
        return report.to_dict()
    if isinstance(report, dict):
        return report
    raise TypeError("report must be a ScanReport or dictionary")


def render_markdown(report: Any) -> str:
    data = _as_dict(report)
    findings = data.get("findings") or []
    top = findings[0] if findings else None
    dbms = data.get("dbms_profile") or {}
    dbms_text = ", ".join(f"{name} {score}%" for name, score in dbms.items()) or "Unknown"
    lines = [
        "# WebSQLMapper SQL Injection Assessment",
        "",
        "## Summary",
        "",
        f"- **Target:** `{data.get('target', '')}`",
        f"- **Method:** `{data.get('method', '')}`",
        f"- **Injection point:** `{data.get('injection_location', 'auto')}:{data.get('parameter', '')}`",
        f"- **Verdict:** **{data.get('verdict', 'unknown')}**",
        f"- **Confidence:** **{data.get('confidence_score', 0)}/100**",
        f"- **Reproducibility:** **{data.get('reproducibility', 0)}%**",
        f"- **Probable DBMS:** {dbms_text}",
        f"- **Requests sent:** {data.get('requests_sent', 0)}",
        f"- **Adaptive early-stop:** {'yes' if data.get('adaptive_stopped') else 'no'}",
        f"- **Interference profile:** {json.dumps(data.get('interference_profile') or {}, ensure_ascii=False)}",
        "- **CWE:** CWE-89 — Improper Neutralization of Special Elements used in an SQL Command",
        "",
        "## Evidence",
        "",
    ]
    if not findings:
        lines.append("No medium-or-higher confidence SQL injection indicator was confirmed.")
    for index, finding in enumerate(findings, 1):
        lines.extend([
            f"### {index}. {finding.get('title', 'Finding')}",
            "",
            f"- Score: {finding.get('score', 0)}/100",
            f"- Confidence: {finding.get('confidence', 'unknown')}",
            f"- Category: `{finding.get('category', '')}`",
            f"- DBMS hint: `{finding.get('dbms_hint') or 'none'}`",
            "",
            "```json",
            json.dumps(finding.get("evidence", {}), indent=2, ensure_ascii=False),
            "```",
            "",
        ])
    lines.extend([
        "## Reproduction timeline",
        "",
        "| # | Phase | Label | Status | Length | Time (ms) | Redirects |",
        "|---:|---|---|---:|---:|---:|---:|",
    ])
    for item in data.get("timeline") or []:
        lines.append(
            f"| {item.get('index')} | {item.get('phase')} | {item.get('label')} | "
            f"{item.get('status')} | {item.get('length')} | {item.get('elapsed_ms')} | {len(item.get('redirects') or [])} |"
        )
    redirect_rows = []
    for item in data.get("timeline") or []:
        for hop in item.get("redirects") or []:
            redirect_rows.append((item, hop))
    if redirect_rows:
        lines.extend([
            "",
            "## Redirect observations",
            "",
            "| Request | Hop | Status | Method | Source | Target | Cross host | HTTPS downgrade |",
            "|---:|---:|---:|---|---|---|---|---|",
        ])
        for item, hop in redirect_rows:
            lines.append(
                f"| {item.get('index')} | {hop.get('index')} | {hop.get('status')} | {hop.get('method')} | "
                f"`{hop.get('url')}` | `{hop.get('location')}` | {bool(hop.get('cross_host'))} | {bool(hop.get('https_downgrade'))} |"
            )
    lines.extend([
        "",
        "## Impact",
        "",
        "If the indicator is confirmed in the application context, SQL injection can allow an attacker to alter the intended database query. Actual impact depends on the affected statement and database privileges.",
        "",
        "## Remediation",
        "",
        "Use parameterized queries/prepared statements, allow-list any unavoidable dynamic identifiers, validate input by expected type, and give the application database account only the privileges it requires.",
        "",
        "## References",
        "",
        "- OWASP SQL Injection Prevention Cheat Sheet",
        "- PortSwigger Web Security Academy — SQL injection",
        "- CWE-89",
        "",
        "_Generated by WebSQLMapper. Review evidence manually before submitting a security report._",
    ])
    return "\n".join(lines) + "\n"


