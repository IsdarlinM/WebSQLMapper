def render_report(report: Any, format_name: str) -> str:
    format_name = format_name.lower()
    if format_name == "json":
        return json.dumps(_as_dict(report), indent=2, ensure_ascii=False) + "\n"
    if format_name == "markdown":
        return render_markdown(report)
    if format_name == "html":
        return render_html(report)
    raise ValueError("report format must be one of: json, markdown, html")


def load_report(path: str | Path) -> dict[str, Any]:
    try:
        data = json.loads(Path(path).read_text(encoding="utf-8"))
    except OSError as exc:
        raise ValueError(f"cannot read report: {exc}") from exc
    except json.JSONDecodeError as exc:
        raise ValueError(f"invalid JSON report: {exc.msg}") from exc
    if not isinstance(data, dict):
        raise ValueError("JSON report root must be an object")
    return data
